it('configures only current own verified recipient and enqueues one atomic minimal notice on the original WA head', async () => {
  const s = await buildSupportScenario(); firebase.db = s.db;
  await seedConsents(s.db, 'demo-web');
  const link = (await readPlatformWhatsAppLinkStatus(token(), s.db)).current!;
  const config = { linkId: link.linkId, expectedRevision: 0, requestId: randomUUID() };
  expect(await configurePlatformSupportRecipient(token(), config, s.db)).toEqual({ revision: 1 });
  expect(await configurePlatformSupportRecipient(token(), config, s.db)).toEqual({ revision: 1 });
  expect(await readPlatformSupportRecipient(token(), s.db)).toEqual({ configured: true, revision: 1, expiresAt: now + 2_592_000_000 });
  const thread = await createSupportConversation('demo-web', randomUUID(), s.db), actor = { uid: 'demo-web', role: 'customer' as const }, input = { requestId: randomUUID(), expectedRevision: 0, text: 'NO COPIAR nombre correo consulta' };
  const message = await appendSupportMessage(actor, thread.id, input, s.db);
  expect((await readSupportMessages(actor, thread.id, null, s.db)).notificationStates).toEqual([{ messageId: message.id, state: 'pending' }]);
  const job = [...s.rows.values()].find(r => r.kind === 'operator_notification')!;
  expect(job).toMatchObject({ uid: 'demo-link-user', sourceKind: expect.any(String), audioState: 'not_applicable', generationState: 'not_applicable' });
  expect(workPayload(job as never, now)).toEqual({ customerPhone: '+12025550101', question: null });
  const lease = (await s.work.claimNext())!; expect(lease?.jobId).toBe(job.jobId);
  const copy = 'Tienes una nueva consulta de soporte en SarinBot. Revísala en tu panel.\nhttps://sarinbotsaas.pages.dev/admin/assistant?support=' + thread.id;
  const out = await s.work.saveReply(lease, copy);
  expect(workPayload(s.rows.get('platformWhatsAppOutbox/' + out.outboxId) as never, now)?.text).toBe(copy);
  expect(await appendSupportMessage(actor, thread.id, input, s.db)).toEqual(message);
  expect([...s.rows.values()].filter(r => r.kind === 'operator_notification')).toHaveLength(1);
  vi.stubEnv('SUPERADMIN_UID', 'other');
  expect(await s.work.claimSend(out.outboxId)).toBeNull();
});
async function scenario() {
  const s = await buildSupportScenario(); firebase.db = s.db; await seedConsents(s.db, 'demo-web');
  const link = (await readPlatformWhatsAppLinkStatus(token(), s.db)).current!;
  await configurePlatformSupportRecipient(token(), { linkId: link.linkId, expectedRevision: 0, requestId: randomUUID() }, s.db);
  return { ...s, thread: await createSupportConversation('demo-web', randomUUID(), s.db), actor: { uid: 'demo-web', role: 'customer' as const } };
}
it.each(['source-erased', 'window-closed', 'budget-zero', 'role-lost', 'disabled'] as const)('stores terminal blocked for %s and never revives old messages after a new inbound', async mode => {
  const s = await scenario();
  if (mode === 'source-erased') for (const [path, row] of s.rows) if (row.recordType === 'event' && row.kind === 'incoming_text') s.seed(path, { ...row, state: 'body_erased', content: null });
  if (mode === 'window-closed') vi.spyOn(Date, 'now').mockReturnValue(now + 86_400_000);
  if (mode === 'budget-zero') vi.stubEnv('PLATFORM_WHATSAPP_SEND_DAILY_BUDGET_MICROS', '0');
  if (mode === 'role-lost') vi.stubEnv('SUPERADMIN_UID', 'other');
  if (mode === 'disabled') firebase.getUser.mockImplementation(async uid => ({ uid, disabled: uid === 'demo-link-user' }));
  const input = { requestId: randomUUID(), expectedRevision: 0, text: 'never requeue' }, message = await appendSupportMessage(s.actor, s.thread.id, input, s.db);
  expect((await readSupportMessages(s.actor, s.thread.id, null, s.db)).notificationStates).toEqual([{ messageId: message.id, state: 'blocked' }]);
  vi.spyOn(Date, 'now').mockReturnValue(now); vi.stubEnv('SUPERADMIN_UID', 'demo-link-user'); vi.stubEnv('PLATFORM_WHATSAPP_SEND_DAILY_BUDGET_MICROS', '100'); firebase.getUser.mockImplementation(async uid => ({ uid, disabled: false }));
  await ingestPlatformWhatsAppEvent(s.event('New independent incoming'), getPlatformWhatsAppConfig(), s.db, now);
  expect(await appendSupportMessage(s.actor, s.thread.id, input, s.db)).toEqual(message);
  expect((await readSupportMessages(s.actor, s.thread.id, null, s.db)).notificationStates[0].state).toBe('blocked');
});
it.each(['role', 'recipient-revoke', 'owner-revoke', 'disabled', 'cutoff'] as const)('revalidates %s before the one-use notice send permit', async loss => {
  const s = await scenario(); await appendSupportMessage(s.actor, s.thread.id, { requestId: randomUUID(), expectedRevision: 0, text: 'private' }, s.db);
  const lease = (await s.work.claimNext())!, job = (await s.work.readAuthorized(lease))!, out = await s.work.saveReply(lease, supportNotificationText(job.supportNotification!)), claim = (await s.work.claimSend(out.outboxId))!;
  if (loss === 'role') vi.stubEnv('SUPERADMIN_UID', 'other');
  if (loss === 'recipient-revoke') await seedConsents(s.db, 'demo-link-user', 2, false);
  if (loss === 'owner-revoke') await seedConsents(s.db, 'demo-web', 2, false);
  if (loss === 'disabled') firebase.getUser.mockImplementation(async uid => ({ uid, disabled: uid === 'demo-link-user' }));
  if (loss === 'cutoff') firebase.getUser.mockImplementation(async uid => ({ uid, disabled: false, tokensValidAfterTime: new Date(now + 1000).toISOString() }));
  expect(await takePlatformSendPermit(out.outboxId, claim.token, s.db)).toBeNull();
  expect(await createPlatformWorkStore(s.db).claimSend(out.outboxId)).toBeNull();
});
it('rechecks path-bound original source contact before sending a saved notice', async () => {
  const s = await scenario(); await appendSupportMessage(s.actor, s.thread.id, { requestId: randomUUID(), expectedRevision: 0, text: 'private' }, s.db);
  const lease = (await s.work.claimNext())!, job = (await s.work.readAuthorized(lease))!, out = await s.work.saveReply(lease, supportNotificationText(job.supportNotification!)), claim = (await s.work.claimSend(out.outboxId))!;
  const path = 'platformWhatsAppEvents/' + job.sourceEventId, source = s.rows.get(path)!;
  s.seed(path, { ...source, content: { ...source.content as object, data: 'AAAA' } });
  await expect(takePlatformSendPermit(out.outboxId, claim.token, s.db)).rejects.toMatchObject({ status: 503 });
  expect(s.rows.get('platformWhatsAppOutbox/' + out.outboxId)?.status).toBe('claimed');
});
